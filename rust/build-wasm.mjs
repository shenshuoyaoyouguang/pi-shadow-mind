// Builds the Rust kernel to wasm32-unknown-unknown and inlines the result into
// the TypeScript bundle as base64, preserving every build invariant of
// scripts/build.mjs (no new runtime deps, no platform binaries, pure ESM).
//
// Run:  node rust/build-wasm.mjs
// Prereqs: rustup target add wasm32-unknown-unknown && cargo install wasm-pack
//
// Output (regenerated in place):
//   src/generated/kernel-wasm.ts   — KERNEL_WASM_BASE64 + KERNEL_WASM_READY=true
//   src/generated/kernel-glue.js   — wasm-bindgen `--target web` glue (with a
//                                    named `init` re-export so the hand-written
//                                    kernel-glue.d.ts stays valid)

import { execSync } from "node:child_process";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const crateDir = resolve(here, "pi-shadow-kernel");
const outDir = resolve(crateDir, "pkg");
const generatedDir = resolve(root, "src", "generated");

function run(cmd, opts) {
  execSync(cmd, { stdio: "inherit", ...opts });
}

// 0. Probe the Rust toolchain. When absent, skip silently so `npm run build`
//    stays green on machines without Rust — the TS fallback in wasm-kernel.ts
//    covers the gap. A real build error (toolchain present but wasm-pack fails)
//    still exits non-zero below.
function hasCommand(cmd) {
  try {
    execSync(cmd, { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function hasWasmTarget() {
  try {
    const out = execSync("rustup target list --installed", { encoding: "utf8" });
    return out.includes("wasm32-unknown-unknown");
  } catch {
    return false;
  }
}

if (!hasCommand("wasm-pack --version")) {
  console.warn("[build-wasm] wasm-pack not found; skipping (TypeScript fallback stays active).");
  process.exit(0);
}
if (!hasWasmTarget()) {
  console.warn(
    "[build-wasm] wasm32-unknown-unknown target not installed; skipping. Install with: rustup target add wasm32-unknown-unknown",
  );
  process.exit(0);
}

// 1. Build the crate to a `--target web` JS glue + .wasm.
console.log("[build-wasm] wasm-pack build --target web");
await rm(outDir, { recursive: true, force: true });
run(`wasm-pack build --target web --out-name kernel --out-dir "${outDir}"`, { cwd: crateDir });

const gluePath = resolve(outDir, "kernel.js");
const wasmPath = resolve(outDir, "kernel_bg.wasm");
let glue = await readFile(gluePath, "utf8");
const wasmBytes = await readFile(wasmPath);

// 2. Ensure the glue exports a named `init` (the hand-written .d.ts declares one).
//    wasm-pack `--target web` exports the init as `default`; re-export it as `init`.
if (!/\bexport\s+function\s+init\b/.test(glue)) {
  if (/\bexport\s+default\b/.test(glue)) {
    glue += "\nexport { default as init };\n";
  } else if (/\b__wbg_init\b/.test(glue)) {
    glue += "\nexport { __wbg_init as init };\n";
  } else {
    throw new Error("Could not find an init/default export in the wasm-bindgen glue.");
  }
}

// 3. Base64-inline the wasm and regenerate the two source modules.
const base64 = wasmBytes.toString("base64");
await mkdir(generatedDir, { recursive: true });

await writeFile(
  resolve(generatedDir, "kernel-wasm.ts"),
  `// AUTO-GENERATED by \`rust/build-wasm.mjs\`. Do not edit by hand.\n` +
    `// The Rust kernel compiled to wasm32, base64-inlined so the ESM bundle stays\n` +
    `// a single file with no platform binaries or new runtime dependencies.\n\n` +
    `export const KERNEL_WASM_BASE64 = ${JSON.stringify(base64)};\n` +
    `export const KERNEL_WASM_READY = true as const;\n`,
);

await writeFile(
  resolve(generatedDir, "kernel-glue.js"),
  `// AUTO-GENERATED by \`rust/build-wasm.mjs\` from wasm-bindgen --target web output.\n` +
    `// Do not edit by hand. Types live in the sibling kernel-glue.d.ts.\n` +
    glue,
);

console.log(`[build-wasm] done — inlined ${wasmBytes.length} wasm bytes (${base64.length} base64 chars).`);
console.log("[build-wasm] next: npm run verify && npm run build");
